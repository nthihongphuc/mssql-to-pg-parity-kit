-- -----------------------------------------------------------------------------
-- Roles (NOLOGIN least-privilege roles)
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_retail_rw') THEN
        CREATE ROLE app_retail_rw NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bi_readonly') THEN
        CREATE ROLE bi_readonly NOLOGIN;
    END IF;
END
$$;

-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.customers (
    customer_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- INTENTIONAL DRIFT #1: Missing NOT NULL constraint (MSSQL source is NOT NULL)
    email_address  VARCHAR(255) UNIQUE,
    full_name      VARCHAR(150) NOT NULL,
    vat_number     VARCHAR(32),
    loyalty_tier   VARCHAR(20)  NOT NULL DEFAULT 'STANDARD',
    created_at_utc TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.products (
    product_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code     VARCHAR(64)    NOT NULL UNIQUE,
    product_name VARCHAR(200)   NOT NULL,
    unit_price   NUMERIC(18,2)  NOT NULL,
    stock_qty    INTEGER        NOT NULL,
    is_active    BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.orders (
    order_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT         NOT NULL REFERENCES public.customers (customer_id),
    order_date_utc TIMESTAMPTZ    NOT NULL,
    total_amount   NUMERIC(18,2)  NOT NULL,
    vat_amount     NUMERIC(18,2)  NOT NULL,
    order_status   VARCHAR(30)    NOT NULL,
    -- INTENTIONAL DRIFT #2: Unmapped abbreviation (source: PromoChannelCode)
    promo_chnl_cd  VARCHAR(32)
);

-- INTENTIONAL DRIFT #3: Missing composite index on orders (customer_id, order_date_utc)

CREATE TABLE IF NOT EXISTS public.order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL REFERENCES public.orders (order_id),
    product_id    BIGINT        NOT NULL REFERENCES public.products (product_id),
    quantity      INTEGER       NOT NULL,
    line_amount   NUMERIC(18,2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_order_items_order_id
    ON public.order_items (order_id);

CREATE TABLE IF NOT EXISTS public.payments (
    payment_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id             BIGINT        NOT NULL REFERENCES public.orders (order_id),
    -- Resolved cleanly via config/name_overrides.yaml (PaymentRefCode -> external_payment_ref)
    external_payment_ref VARCHAR(64)   NOT NULL UNIQUE,
    paid_amount          NUMERIC(18,2) NOT NULL,
    paid_at_utc          TIMESTAMPTZ   NOT NULL,
    payment_method       VARCHAR(32)   NOT NULL
);

-- Resolved cleanly via config/name_overrides.yaml (LegacyAuditLog -> archive_audit_events)
CREATE TABLE IF NOT EXISTS public.archive_audit_events (
    audit_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name    VARCHAR(64) NOT NULL,
    event_payload  TEXT,
    logged_at_utc  TIMESTAMPTZ NOT NULL
);

