-- -----------------------------------------------------------------------------
-- Functions (PL/pgSQL ports; usp_ArchiveOldOrders intentionally omitted)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_get_customer_orders(p_customer_id BIGINT)
RETURNS TABLE (
    order_id       BIGINT,
    order_date_utc TIMESTAMPTZ,
    total_amount   NUMERIC(18,2),
    vat_amount     NUMERIC(18,2),
    order_status   VARCHAR(30)
)
LANGUAGE sql
STABLE
AS $$
    SELECT order_id, order_date_utc, total_amount, vat_amount, order_status
    FROM public.orders
    WHERE customer_id = p_customer_id
    ORDER BY order_date_utc DESC;
$$;

CREATE OR REPLACE FUNCTION public.fn_calculate_order_vat(p_order_id BIGINT, p_vat_rate NUMERIC(5,4))
RETURNS NUMERIC(18,2)
LANGUAGE sql
STABLE
AS $$
    SELECT ROUND(total_amount * p_vat_rate, 2)
    FROM public.orders
    WHERE order_id = p_order_id;
$$;

